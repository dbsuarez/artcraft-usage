"""Generate <tool>/REFERENCE.md: every command a CLI offers, with its parameters, from the CLI's own catalogue.

Run after installing or updating a tool:  python tools/gen_reference.py [deckcraft wordcraft ...]
Agents search REFERENCE.md (grep the command id or a word) instead of running help, commands, or describe.
"""

import json
import os
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PROGRAMS = r"C:\Program Files"


def exe(tool):
    name = {"deckcraft": "DeckCraft", "wordcraft": "WordCraft", "pdfcraft": "PdfCraft",
            "soundcraft": "SoundCraft", "vectorcraft": "VectorCraft", "photocraft": "PhotoCraft"}[tool]
    return os.path.join(PROGRAMS, name, f"{tool}-cli.exe")


def sh(*args):
    r = subprocess.run(list(args), capture_output=True, text=True, encoding="utf-8", errors="replace")
    if r.returncode != 0:
        raise SystemExit(f"{' '.join(args)} failed:\n{r.stderr[-2000:]}")
    return r.stdout


def clean(text):
    """One line, plain hyphens (no en or em dashes), pipes escaped for Markdown tables."""
    text = " ".join(str(text or "").split())
    return text.replace("\u2014", "-").replace("\u2013", "-").replace("|", "\\|")


def table(rows, head=("Command", "Label", "Parameters")):
    out = ["| " + " | ".join(head) + " |", "|" + " --- |" * len(head)]
    out += ["| " + " | ".join(clean(c) for c in row) + " |" for row in rows]
    return out


def deckcraft():
    rows = []
    for line in sh(exe("deckcraft"), "commands").splitlines():
        if not line.strip():
            continue
        cid, _, rest = line.partition(" \u2014 ")
        label, _, params = rest.partition(": ")
        rows.append((f"`{cid.strip()}`", label, params))
    return "Run with `deckcraft-cli run --cmd 'id={json}'` (see NOTES.md).", table(rows)


def wordcraft():
    cmds = json.loads(sh(exe("wordcraft"), "commands", "--json"))
    rows = [(f"`{c['id']}`", c.get("label", ""), c.get("params", "")) for c in cmds]
    return "Use in a `run --script` JSON file as `{\"command\": id, \"params\": {...}}` (see NOTES.md).", table(rows)


def vectorcraft():
    cmds = json.loads(sh(exe("vectorcraft"), "commands"))
    rows = [(f"`{c['id']}`", c.get("label", ""), c.get("params", "")) for c in cmds]
    return "Use with `vectorcraft-cli run --cmd ID --params JSON` or a `--commands` file (see NOTES.md).", table(rows)


def photocraft():
    cmds = json.loads(sh(exe("photocraft"), "commands", "--json"))
    rows = [(f"`{c['id']}`", c.get("label", ""), c.get("params", "")) for c in cmds]
    return "Use with `photocraft-cli run` or `photolib.py` (see NOTES.md).", table(rows)


def soundcraft():
    ids = [line.split()[0] for line in sh(exe("soundcraft"), "commands").splitlines() if line.strip()]

    def describe(cid):
        d = json.loads(sh(exe("soundcraft"), "describe", cid))
        return (f"`{cid}`", d.get("label", ""), d.get("params", "") or "")

    with ThreadPoolExecutor(8) as pool:
        rows = list(pool.map(describe, ids))
    return "Use with `soundcraft-cli run --cmd ID=JSON` or one `ID JSON` per line in a `script` file (see NOTES.md).", table(rows)


def pdfcraft():
    data = json.loads(sh(exe("pdfcraft"), "tools"))
    tools = data if isinstance(data, list) else next(v for v in data.values() if isinstance(v, list))
    lines = []
    for t in tools:
        schema = t.get("inputSchema") or t.get("input_schema") or t.get("parameters") or {}
        required = set(schema.get("required") or [])
        lines += [f"### {t['name']}", "", clean(t.get("description")), ""]
        for name, p in (schema.get("properties") or {}).items():
            kind = p.get("type", "")
            if "enum" in p:
                kind = " \\| ".join(json.dumps(e) for e in p["enum"])
            req = ", required" if name in required else ""
            desc = clean(p.get("description"))
            lines.append(f"- `{name}` ({kind}{req})" + (f": {desc}" if desc else ""))
        lines.append("")
    return ("Use in `pdfcraft-cli run --script steps.json` as `{\"tool\": name, \"args\": {...}}`, "
            "or `pdfcraft-cli run <tool> key=value` (see NOTES.md)."), lines


GENERATORS = {"deckcraft": deckcraft, "wordcraft": wordcraft, "pdfcraft": pdfcraft,
              "soundcraft": soundcraft, "vectorcraft": vectorcraft, "photocraft": photocraft}


def main(names):
    for tool in names or GENERATORS:
        how, body = GENERATORS[tool]()
        count = sum(1 for line in body if line.startswith("| `") or line.startswith("### "))
        text = "\n".join([
            f"# {tool} command reference",
            "",
            f"Generated by `tools/gen_reference.py` from `{tool}-cli` ({count} commands). Do not edit by hand.",
            "Search this file for a command id or a word; do not read it top to bottom. " + how,
            "",
            *body,
        ]) + "\n"
        os.makedirs(os.path.join(ROOT, tool), exist_ok=True)
        path = os.path.join(ROOT, tool, "REFERENCE.md")
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print(f"{tool}: {count} commands, {len(text.encode('utf-8')) // 1024} KB -> {path}")


if __name__ == "__main__":
    main(sys.argv[1:])
